"""Compile tools/gr4v120/awbml/awbml.c and write core/src/fw/gr4v120/aspect/awbml-code.ts (module) and awbml-data.ts (table blob).

Mirrors tools/cpulut/gen.py: the module is position independent (-fropi -frwpi, no global data, every address passed in
through its context argument); this is checked by linking it at two addresses and comparing, by refusing any
.data/.bss/.rodata/.got section, any undefined symbol (no float / 64-bit division libcalls: the link uses no library)
and by requiring the entry `awbml` at offset 0. The data blob (and the constants shared with the C code, awbml_const.h)
come from ref.py.
"""
import base64
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import ref

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SRC = HERE / 'awbml.c'
HDR = HERE / 'awbml_const.h'
OUT_CODE = ROOT / 'core' / 'src' / 'fw' / 'gr4v120' / 'aspect' / 'awbml-code.ts'
OUT_DATA = ROOT / 'core' / 'src' / 'fw' / 'gr4v120' / 'aspect' / 'awbml-data.ts'
USE_ZIG = bool(os.environ.get('GRMOD_ZIG')) or not (shutil.which('clang') and shutil.which('ld.lld') and shutil.which('llvm-objcopy'))
FLAGS = ['-mcpu=cortex_a7' if USE_ZIG else '-mcpu=cortex-a7', '-marm', '-mfloat-abi=soft', '-O2', '-fomit-frame-pointer',
         '-ffreestanding', '-fno-builtin', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-nostdlib',
         '-fropi', '-frwpi', '-fno-jump-tables', '-Wall', '-Wextra', '-Werror']


def tools():
    if not USE_ZIG:
        return ['clang', '-target', 'armv7-none-eabi'], ['ld.lld'], ['llvm-objcopy']
    z = [sys.executable, '-m', 'ziglang']
    return z + ['cc', '-target', 'arm-freestanding-eabi'], z + ['ld.lld'], z + ['objcopy']


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'{" ".join(map(str, cmd))}\n{r.stdout}{r.stderr}')
    return r.stdout


def build(cc, ld, objcopy, tmp, origin, extra=()):
    obj = tmp / 'am.o'
    run(cc + FLAGS + ['-I', HERE] + list(extra) + ['-c', SRC, '-o', obj])
    elf = tmp / f'am_{origin:x}.elf'
    run(ld + [f'-Ttext=0x{origin:x}', '--entry=awbml', '-o', elf, obj])   # no library: an undefined symbol is an error
    out = tmp / f'am_{origin:x}.bin'
    run(objcopy + ['-O', 'binary', '-j', '.text', elf, out])
    sections = run(['readelf', '-S', '-W', elf])
    for name in ('.data', '.bss', '.rodata', '.got'):
        if f' {name} ' in sections or f' {name}.' in sections:
            sys.exit(f'module has a {name} section')
    symbols = run(['readelf', '-s', '-W', elf])
    entry = [l for l in symbols.splitlines() if l.strip().endswith(' awbml')]
    if not entry or int(entry[0].split()[1], 16) != origin:
        sys.exit('awbml is not at the start of .text')
    if any(' UND ' in l and l.split()[1:2] != ['00000000'] for l in symbols.splitlines()[3:]):
        sys.exit('undefined symbols')
    return out.read_bytes()


def stack_usage(cc, tmp):
    run(cc + FLAGS + ['-I', HERE, '-fstack-usage', '-c', SRC, '-o', tmp / 'su.o'])
    rows = {}
    if not (tmp / 'su.su').exists():
        print('compiler emitted no static .su report; use ARM runtime stack measurements', file=sys.stderr)
        return {}
    for l in (tmp / 'su.su').read_text().splitlines():
        p = l.split('\t')
        rows[p[0].split(':')[-1]] = int(p[1])
    return rows


def ts_hex_offsets(offs):
    return ''.join(f"  {n}: {offs[n]},\n" for n in ref.TABLE_ORDER)


def main():
    HDR.write_text(ref.const_header())
    cc, ld, objcopy = tools()
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        a = build(cc, ld, objcopy, tmp, 0x10000)
        b = build(cc, ld, objcopy, tmp, 0x54430000)
        su = stack_usage(cc, tmp)
    if a != b:
        sys.exit('module is not position independent')
    while len(a) % 4:
        a += b'\0'
    version = run(cc + ['--version']).splitlines()[0]
    src_hash = hashlib.sha256(SRC.read_bytes() + HDR.read_bytes()).hexdigest()
    OUT_CODE.write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr4v120/awbml/gen.py from tools/gr4v120/awbml/awbml.c (+ awbml_const.h) -- do not edit.\n'
        f'// Compiler: {version}\n'
        f'// Source SHA-256 (awbml.c followed by awbml_const.h): {src_hash}\n'
        '// Position independent: entry `awbml(ctx, obj, S)` at offset 0; ctx layout in awbml.c (struct awbml_ctx).\n\n'
        f"export const AWBML_CODE = '{base64.b64encode(a).decode()}';\n"
        f'export const AWBML_CODE_LENGTH = {len(a)};\n'
        f'export const AWBML_SCRATCH_BYTES = {ref.SCRATCH_BYTES};\n'
        f'export const AWBML_MAGIC = 0x{ref.MAGIC:08x};\n'
        f'export const AWBML_PERIOD = {ref.PERIOD};\n'
        f"export const AWBML_SOURCE_SHA256 = '{src_hash}';\n")
    tab, blob, offs = ref.build_tables()
    blob_hash = hashlib.sha256(blob).hexdigest()
    OUT_DATA.write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr4v120/awbml/gen.py from tools/gr4v120/awbml/ref.py (model parameters ffcc_cube_meta.npz, calibration cal.json) -- do not edit.\n'
        '// Table blob for awbml-code.ts, little endian, every table 4-byte aligned; byte offsets of each table in AWBML_OFFSETS\n'
        '// (layout and element types: docstring of tools/gr4v120/awbml/ref.py; the context pointers are data base + offset).\n\n'
        f"export const AWBML_DATA = '{base64.b64encode(blob).decode()}';\n"
        f'export const AWBML_DATA_LENGTH = {len(blob)};\n'
        f"export const AWBML_DATA_SHA256 = '{blob_hash}';\n"
        'export const AWBML_OFFSETS = {\n' + ts_hex_offsets(offs) + '} as const;\n')
    print(f'{OUT_CODE}: {len(a)} bytes')
    print(f'{OUT_DATA}: {len(blob)} bytes, sha256 {blob_hash}')
    print('offsets', offs)
    print('stack usage per function (bytes):', su)


if __name__ == '__main__':
    main()
