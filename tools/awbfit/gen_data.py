#!/usr/bin/env python3
"""Write core/src/fw/aspect/awbfit-data.ts from a fitted table file (npz with T2, T4, T5: uint8 24 x 33, [row][column])."""
import sys, os, hashlib
import numpy as np

src, dst = sys.argv[1], sys.argv[2]
z = np.load(src)
parts = []
for name in ('T2', 'T4', 'T5'):
    t = np.asarray(z[name], dtype=np.uint8)
    assert t.shape == (24, 33), (name, t.shape)
    parts.append((name, t.tobytes().hex()))
h = hashlib.sha256(b''.join(bytes.fromhex(x) for _, x in parts)).hexdigest()[:16]
with open(dst, 'w') as f:
    f.write('// SPDX-License-Identifier: GPL-2.0-only\n')
    f.write(f'// Generated by tools/awbfit/gen_data.py from {os.path.basename(src)} (sha256 of the three tables {h}).\n')
    f.write('// Plain-Auto AWB tables, 24 rows (EV -5..18) x 33 light-source frames, firmware order table[row * 33 + frame].\n')
    for name, x in parts:
        f.write(f"export const AWB_FIT_{name} = '{x}';\n")
print(dst, h)
